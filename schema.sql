-- Run this in Supabase Dashboard > SQL Editor.
-- Public visitors can read approved listings and submit pending listings only.
-- Never put a Supabase service_role key in the website.

create table if not exists public.listings (
  id bigint generated by default as identity primary key,
  business_name text not null check (char_length(business_name) between 2 and 100),
  category text not null check (category in ('shops','technical','food','transport','beauty','property','education','other')),
  city text not null check (char_length(city) between 2 and 70),
  description text not null check (char_length(description) between 10 and 1500),
  phone text,
  whatsapp text,
  website text,
  contact_name text not null check (char_length(contact_name) between 2 and 100),
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now()
);

alter table public.listings enable row level security;

drop policy if exists "Anyone can view approved listings" on public.listings;
create policy "Anyone can view approved listings"
on public.listings for select
to anon, authenticated
using (status = 'approved');

drop policy if exists "Anyone can submit pending listings" on public.listings;
create policy "Anyone can submit pending listings"
on public.listings for insert
to anon, authenticated
with check (status = 'pending');

-- Admin moderation:
-- 1) Create your own user in Supabase Authentication > Users (invite/sign up).
-- 2) In SQL Editor, create an admin role table and add only your own auth user UUID.
create table if not exists public.site_admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);
alter table public.site_admins enable row level security;

drop policy if exists "Admins can read admin list" on public.site_admins;
create policy "Admins can read admin list"
on public.site_admins for select
to authenticated
using (auth.uid() = user_id);

drop policy if exists "Admins can view all listings" on public.listings;
create policy "Admins can view all listings"
on public.listings for select
to authenticated
using (exists (select 1 from public.site_admins a where a.user_id = auth.uid()));

drop policy if exists "Admins can update listings" on public.listings;
create policy "Admins can update listings"
on public.listings for update
to authenticated
using (exists (select 1 from public.site_admins a where a.user_id = auth.uid()))
with check (exists (select 1 from public.site_admins a where a.user_id = auth.uid()));

